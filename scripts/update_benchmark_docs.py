#!/usr/bin/env python3
"""Generate Markdown tables from the comparison benchmark results."""

import json
import os
import platform
from datetime import datetime, timezone
from pathlib import Path


WORKSPACE_ROOT = Path(__file__).resolve().parent.parent
SCENARIOS = (
    ("Linting_1_commit_hook", "Current commit", 1),
    ("Linting_10_commits", "10-commit history range", 10),
)
TOOLS = ("commitfmt", "commitlint")


def criterion_dir() -> Path:
    target_dir = Path(os.environ.get("CARGO_TARGET_DIR", WORKSPACE_ROOT / "target"))
    if not target_dir.is_absolute():
        target_dir = WORKSPACE_ROOT / target_dir
    return target_dir / "criterion"


def read_estimate(directory: str, tool: str) -> dict[str, float]:
    path = criterion_dir() / directory / tool / "new" / "estimates.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise SystemExit(
            f"Benchmark result not found: {path}\n"
            "Run `make benchmark-comparison` to generate it."
        ) from error

    mean = data["mean"]
    confidence = mean["confidence_interval"]
    return {
        "mean": mean["point_estimate"],
        "lower": confidence["lower_bound"],
        "upper": confidence["upper_bound"],
    }


def format_duration(nanoseconds: float) -> str:
    return f"{nanoseconds / 1_000_000:.1f} ms"


def format_estimate(estimate: dict[str, float]) -> str:
    mean = format_duration(estimate["mean"])
    lower = estimate["lower"] / 1_000_000
    upper = estimate["upper"] / 1_000_000
    return f"{mean} ({lower:.1f}–{upper:.1f} ms)"


def read_commitlint_version() -> str:
    package_path = (
        WORKSPACE_ROOT / "crates" / "commitfmt-benchmark" / "comparison" / "package.json"
    )
    package = json.loads(package_path.read_text(encoding="utf-8"))
    return package["devDependencies"]["@commitlint/cli"]


def read_commitfmt_version() -> str:
    manifest_path = WORKSPACE_ROOT / "crates" / "commitfmt" / "Cargo.toml"
    for line in manifest_path.read_text(encoding="utf-8").splitlines():
        if line.startswith("version = "):
            return line.split('"', 2)[1]
    raise SystemExit(f"Unable to read commitfmt version from {manifest_path}")


def platform_name() -> str:
    system = platform.system()
    if system == "Darwin":
        system = "macOS"
        release = platform.mac_ver()[0]
    else:
        release = platform.release()
    return f"{system} {release} ({platform.machine()})"


def generate_markdown() -> str:
    results = {
        directory: {tool: read_estimate(directory, tool) for tool in TOOLS}
        for directory, _, _ in SCENARIOS
    }
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "<!-- Generated by scripts/update_benchmark_docs.py. Do not edit manually. -->",
        "",
        "# commitfmt vs commitlint benchmark",
        "",
        "The comparison benchmark runs both tools as separate processes with equivalent lint rules. The commit hook scenario checks `COMMIT_EDITMSG`; the history scenario checks the range `HEAD~10..HEAD`.",
        "",
        "Run `make benchmark-comparison` to repeat the measurements and update this document.",
        "",
        "## Environment",
        "",
        "| Property | Value |",
        "| --- | --- |",
        f"| Generated | {generated_at} |",
        f"| Platform | {platform_name()} |",
        f"| commitfmt | {read_commitfmt_version()} (`dist` profile) |",
        f"| commitlint | {read_commitlint_version()} |",
        "",
        "## Mean latency",
        "",
        "Lower is better. Values in parentheses are the 95% confidence interval.",
        "",
        "| Scenario | Messages per run | commitfmt | commitlint | Speedup |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]

    for directory, label, messages in SCENARIOS:
        commitfmt = results[directory]["commitfmt"]
        commitlint = results[directory]["commitlint"]
        speedup = commitlint["mean"] / commitfmt["mean"]
        lines.append(
            f"| {label} | {messages} | {format_estimate(commitfmt)} | "
            f"{format_estimate(commitlint)} | {speedup:.1f}× |"
        )

    lines.extend(
        [
            "",
            "## Throughput",
            "",
            "Higher is better. Throughput is calculated from the mean latency and the number of messages checked per run.",
            "",
            "| Scenario | commitfmt | commitlint |",
            "| --- | ---: | ---: |",
        ]
    )

    for directory, label, messages in SCENARIOS:
        commitfmt_rate = messages * 1_000_000_000 / results[directory]["commitfmt"]["mean"]
        commitlint_rate = messages * 1_000_000_000 / results[directory]["commitlint"]["mean"]
        lines.append(
            f"| {label} | {commitfmt_rate:.1f} messages/s | "
            f"{commitlint_rate:.1f} messages/s |"
        )

    lines.extend(
        [
            "",
            "Results depend on hardware and system load. See the [benchmark source](../crates/commitfmt-benchmark/benches/comparison.rs) for the exact configuration.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    output_path = WORKSPACE_ROOT / "docs" / "benchmark.md"
    output_path.write_text(generate_markdown(), encoding="utf-8")
    print(f"Updated {output_path.relative_to(WORKSPACE_ROOT)}")


if __name__ == "__main__":
    main()
